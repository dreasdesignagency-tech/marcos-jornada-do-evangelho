/** Em quais capítulos o item é útil (calculado dos dados). */
export function usedIn(chapters: { n: number; npcs: any[]; side: any[]; steps: any[] }[], id: string): number[] {
  const set = new Set<number>();
  for (const c of chapters) {
    if (c.npcs.some((n) => n.uses?.some((u: any) => u.item === id))) set.add(c.n);
    if (c.side.some((q) => q.needs === id)) set.add(c.n);
    if (c.steps.some((s) => s.helpItem === id)) set.add(c.n);
  }
  return [...set].sort((a, b) => a - b);
}
